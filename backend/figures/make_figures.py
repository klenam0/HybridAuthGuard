"""
Figures 1-6 for the JCS article. Figures 1 and 2 are line-art diagrams of
the frozen system (figures/diagrams.py; every box is traced to a file:line
at the v3.0.0-frozen tag). Figures 3-6 are drawn from saved results only.

Reads (never writes) results/phase6_primary.json, results/phase6_s1.json,
results/phase4b_diag.json and results/phase4b_confirm.json. No metric is
computed here: every plotted number is read from a JSON path, and the same
values and paths are written to FIGURE_DATA.md next to the figures.

Output, per figure: figN_<name>.tif (RGB, no alpha, LZW, 900 dpi, cropped to
the ink) and figN_<name>_preview.png (150 dpi).

    python figures/make_figures.py          (from backend/; needs matplotlib)
    python figures/make_figures.py 1 2 3    write only these figures; the others
                                            are drawn but not saved, and their
                                            FIGURE_DATA.md size line is read from
                                            the .tif already on disk
"""
import io
import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.ticker import FixedLocator, FuncFormatter, NullLocator
from PIL import Image, ImageChops

from diagrams import FIG1_STEM, FIG2_STEM, figure1, figure2

HERE = Path(__file__).resolve().parent
RESULTS = HERE.parent / "results"

DPI = 900
PREVIEW_DPI = 150
MAX_W_CM, MAX_H_CM = 16.51, 20.0
CM = 1 / 2.54

# Paul Tol "high contrast": colour-blind safe, distinct in greyscale
# (dark blue, medium red, light yellow). Bars carry black outlines.
DARK, MID, LIGHT = "#004488", "#BB5566", "#DDAA33"

plt.rcParams.update({
    "font.family": "Arial", "font.size": 9, "axes.titlesize": 9, "axes.labelsize": 9,
    "xtick.labelsize": 8, "ytick.labelsize": 8, "legend.fontsize": 8,
    "text.color": "black", "axes.labelcolor": "black", "axes.edgecolor": "black",
    "xtick.color": "black", "ytick.color": "black", "axes.linewidth": 0.6,
    "xtick.major.width": 0.6, "ytick.major.width": 0.6, "lines.linewidth": 0.8,
    "patch.linewidth": 0.6, "hatch.linewidth": 0.6, "hatch.color": "black",
    "axes.spines.top": False, "axes.spines.right": False, "legend.frameon": False,
    "svg.fonttype": "none", "axes.unicode_minus": False,
})
ERR = dict(ecolor="black", elinewidth=0.8, capsize=2.5, capthick=0.8)
BAR = dict(edgecolor="black", linewidth=0.6)

DETECTORS = ["Brute Force Attack", "Slow Brute Force", "Credential Stuffing",
             "Invalid Account Spraying", "Distributed Brute Force",
             "Success After Failures", "Multiple IP Login", "Suspicious Login Time"]


WRITE = None      # figure stems to write; None = all (set in main)


def load(name):
    with open(RESULTS / name, encoding="utf-8") as f:
        return json.load(f)


def get(doc, path):
    """Value at a '/'-separated JSON path."""
    v = doc
    for k in path.strip("/").split("/"):
        v = v[k]
    return v


class Ledger:
    """Records every plotted value with its source file and JSON path."""

    def __init__(self):
        self.sections = []

    def section(self, title, notes):
        self.sections.append({"title": title, "notes": notes, "rows": []})

    def row(self, label, src, doc, path, role="value"):
        v = get(doc, path)
        self.sections[-1]["rows"].append((label, role, v, src, path))
        return v

    def markdown(self):
        out = ["# Figure data (Figures 1-6)", "",
               "Generated by `backend/figures/make_figures.py`; do not edit by hand.",
               "Figures 1 and 2: every box is listed with the file:line behind it.",
               "Figures 3-6: every plotted bar, point and error bar is listed with its",
               "source file (under `backend/results/`) and JSON path. Values are the full",
               "stored floats; labels printed in the figures are these values rounded as",
               "stated.",
               ""]
        for s in self.sections:
            out += [f"## {s['title']}", ""] + s["notes"] + [""]
            if "boxes" in s:
                out += ["| Box | File:line | Code at that line |", "|---|---|---|"]
                for label, where, code in s["boxes"]:
                    out.append(f"| {label} | `{where}` | `{code}` |")
                out.append("")
                continue
            out += ["| Plotted item | Role | Value | File | JSON path |",
                    "|---|---|---|---|---|"]
            for label, role, v, src, path in s["rows"]:
                out.append(f"| {label} | {role} | {v!r} | `{src}` | `{path}` |")
            out.append("")
        return "\n".join(out)


def save(fig, stem, ledger_notes):
    """Render at 900 dpi, drop alpha, crop to the ink, check the size limits,
    write the .tif and a 150 dpi .png preview. A figure not selected in
    WRITE is not written; its size line is read from the .tif on disk."""
    if WRITE is not None and stem not in WRITE:
        plt.close(fig)
        with Image.open(HERE / f"{stem}.tif") as im:
            w, h = im.size
        ledger_notes.append(f"Output: `{stem}.tif`, {w} x {h} px at {DPI} dpi "
                            f"= {w / DPI * 2.54:.2f} cm x {h / DPI * 2.54:.2f} cm; "
                            f"preview `{stem}_preview.png`.")
        return
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=DPI, facecolor="white", bbox_inches="tight",
                pad_inches=0.02)
    plt.close(fig)
    buf.seek(0)
    im = Image.open(buf).convert("RGB")
    bg = Image.new("RGB", im.size, (255, 255, 255))
    box = ImageChops.difference(im, bg).getbbox()
    im = im.crop(box)
    w_cm, h_cm = im.width / DPI * 2.54, im.height / DPI * 2.54
    assert w_cm <= MAX_W_CM and h_cm <= MAX_H_CM, (stem, w_cm, h_cm)
    # Through a buffer: libtiff handed this process's file descriptor
    # crashes on some Windows builds (CRT mismatch); the bytes are the same.
    tif = io.BytesIO()
    im.save(tif, format="TIFF", compression="tiff_lzw", dpi=(DPI, DPI))
    (HERE / f"{stem}.tif").write_bytes(tif.getvalue())
    pw, ph = round(im.width * PREVIEW_DPI / DPI), round(im.height * PREVIEW_DPI / DPI)
    im.resize((pw, ph), Image.LANCZOS).save(HERE / f"{stem}_preview.png",
                                            dpi=(PREVIEW_DPI, PREVIEW_DPI))
    ledger_notes.append(f"Output: `{stem}.tif`, {im.width} x {im.height} px at {DPI} dpi "
                        f"= {w_cm:.2f} cm x {h_cm:.2f} cm; preview `{stem}_preview.png`.")


def comma(x, _=None):
    return f"{x:,.0f}"


# ── Figure 3: alert precision per detector, May, new attackers ──────────────

def figure3(L, P, S1):
    src = "phase6_primary.json"
    L.section("Figure 3: alert precision per detector, May, new attackers", [
        "New attackers: events whose IP has no attack-labelled event before 1 May;",
        "benign IPs stay in. Bars: `precision` (attack alerts / alerts). Error bars:",
        "`ci_low`, `ci_high`, 95% percentile interval, IPs resampled with replacement",
        "(IP-address-clustered bootstrap, `eval/phase3b.bootstrap`, called in",
        "`eval/phase6_primary.p1`). Labels rounded to 4 decimals; `alerts` is listed",
        "for reference (not plotted).",
        "Dashed line: the event base rate of the same May new-attacker population",
        "(attack events / events), a reference, not a detector result. It is not",
        "stored in `phase6_primary.json`; it is read from `phase6_s1.json`",
        "`base_rate/new_attackers`. Both files use the same mask",
        "(`eval/phase6.Stream6.strata[\"new_attackers\"]` within the May half), and",
        "the stratum's May event count is the same in both (listed below). The line",
        "marks the base rate on the precision axis, so it is vertical on the page",
        "(the bars are horizontal).",
        "The returning-attacker panel (formerly panel B; every bar 1.000 by",
        "construction) was removed at supervisor review.",
    ])
    base = "results/may/P1/strata"
    st = "new_attackers"
    vals = {}
    for d in DETECTORS:
        p = f"{base}/{st}/{d}"
        vals[d] = (L.row(f"{st}, {d}", src, P, f"{p}/precision", "bar"),
                   L.row(f"{st}, {d}", src, P, f"{p}/ci_low", "CI low"),
                   L.row(f"{st}, {d}", src, P, f"{p}/ci_high", "CI high"),
                   L.row(f"{st}, {d}", src, P, f"{p}/alerts", "alerts (not plotted)"))
    rate = L.row("new_attackers, May", "phase6_s1.json", S1, "base_rate/new_attackers",
                 "base rate (dashed line)")
    n_s1 = L.row("new_attackers, May", "phase6_s1.json", S1, "events/new_attackers",
                 "events (not plotted)")
    n_p = L.row("new_attackers, May", src, P, "results/may/P3/response_cost/new_attackers/events",
                "events (not plotted)")
    assert n_s1 == n_p, (n_s1, n_p)

    fig, a = plt.subplots(figsize=(16.0 * CM, 7.6 * CM))
    y = np.arange(len(DETECTORS))[::-1]
    xmax = 0.0145
    prec = np.array([vals[d][0] for d in DETECTORS])
    lo = np.array([vals[d][1] for d in DETECTORS])
    hi = np.array([vals[d][2] for d in DETECTORS])
    a.barh(y, prec, height=0.62, color=DARK, **BAR)
    a.errorbar(prec, y, xerr=[prec - lo, hi - prec], fmt="none", **ERR)
    for yi, p_, h_, d in zip(y, prec, hi, DETECTORS):
        txt = f"{p_:.4f}"
        if p_ == 0:  # an empty bar: say why
            txt += f" (0 of {vals[d][3]:,} alerts)"
        a.text(max(h_, p_) + xmax * 0.015, yi, txt, va="center", fontsize=8)
    a.axvline(rate, color="black", linestyle=(0, (4, 3)), linewidth=0.7, zorder=1.5,
              label=f"Base rate, new attackers ({rate:.4f})")
    a.set_xlim(0, xmax)
    a.xaxis.set_major_locator(FixedLocator([0, 0.004, 0.008, 0.012]))
    a.xaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:.3f}"))
    a.set_xlabel("Alert precision, new attackers")
    a.tick_params(axis="y", length=0)
    a.set_yticks(y, DETECTORS)
    a.set_ylim(-0.6, len(DETECTORS) - 0.4)
    a.legend(loc="upper right", handlelength=2.4, handletextpad=0.4)
    fig.subplots_adjust(top=0.86, left=0.21, right=0.99)
    save(fig, "fig3_detector_precision_new_vs_returning", L.sections[-1]["notes"])


# ── Figure 4: mean daily incident precision vs budget, T2 vs T0, May ───────

def figure4(L, P):
    src = "phase6_primary.json"
    budgets = sorted(get(P, "results/may/P2/curves/T2/all/budgets"), key=int)
    assert budgets == sorted(get(P, "results/may/P2/curves/T0/all/budgets"), key=int)
    L.section("Figure 4: mean daily incident precision vs daily budget, T2 vs T0, May", [
        f"Stratum: all events. Budgets plotted: exactly those stored ({', '.join(budgets)}"
        " incidents per day); points are not joined and nothing is interpolated.",
        "Points: `mean_daily_precision` (mean over the 31 May days of the day's",
        "incident precision among the top-B incidents). Error bars: `daily_ci_low`,",
        "`daily_ci_high`, 95% percentile interval with days resampled with replacement",
        "(day-clustered bootstrap, `eval/phase5.day_bootstrap`). T2 and T0 are drawn",
        "slightly apart horizontally (x 0.95 and x 1.05 of the budget on the log axis)",
        "so the intervals do not overlap; the tick marks the budget.",
    ])
    fig, ax = plt.subplots(figsize=(9.0 * CM, 7.0 * CM))
    for name, color, marker, dodge, label in (("T2", DARK, "o", 0.95, "T2"),
                                              ("T0", MID, "s", 1.05, "T0 (triage baseline)")):
        m, lo, hi = [], [], []
        for B in budgets:
            p = f"results/may/P2/curves/{name}/all/budgets/{B}"
            m.append(L.row(f"{name}, B = {B}", src, P, f"{p}/mean_daily_precision", "point"))
            lo.append(L.row(f"{name}, B = {B}", src, P, f"{p}/daily_ci_low", "CI low"))
            hi.append(L.row(f"{name}, B = {B}", src, P, f"{p}/daily_ci_high", "CI high"))
        x = np.array([int(B) for B in budgets]) * dodge
        m, lo, hi = map(np.array, (m, lo, hi))
        ax.errorbar(x, m, yerr=[m - lo, hi - m], fmt=marker, color=color, ms=5,
                    mec="black", mew=0.6, label=label, linestyle="none", **ERR)
    ax.set_xscale("log")
    ax.xaxis.set_major_locator(FixedLocator([int(B) for B in budgets]))
    ax.xaxis.set_minor_locator(NullLocator())
    ax.xaxis.set_major_formatter(FuncFormatter(comma))
    ax.set_xlim(70, 2900)
    ax.set_ylim(0, 0.6)
    ax.set_xlabel("Daily budget (incidents per day)")
    ax.set_ylabel("Mean daily incident precision")
    ax.legend(loc="upper right", handletextpad=0.3)
    save(fig, "fig4_budget_curve_T2_vs_T0", L.sections[-1]["notes"])


# ── Figure 5: step-up tier precision, val_a, val_b, May ─────────────────────

def figure5(L, P):
    src = "phase6_primary.json"
    halves = ("val_a", "val_b", "may")
    L.section("Figure 5: step-up tier precision on val_a, val_b and May", [
        "Bars: `precision` of the step-up tier (attack incidents / incidents), frozen",
        "system with the floor. Error bars: `ci_low`, `ci_high`, 95% percentile",
        "interval, IPs resampled with replacement (IP-address-clustered bootstrap,",
        "`eval/phase5.region_metrics` via `eval/phase5b.band`). Labels rounded to 3 decimals.",
        "val_a and val_b are both hatched (the JSON flag `previously_seen` is `true`",
        "for both, listed below): val_a is labelled \"rate selected here\" and val_b",
        "\"previously seen\". May (unseen, flag `false`) is unhatched.",
    ])
    fig, ax = plt.subplots(figsize=(9.5 * CM, 7.0 * CM))
    style = {"val_a": dict(color=LIGHT, hatch="////"), "val_b": dict(color=LIGHT, hatch="////"),
             "may": dict(color=DARK)}
    ticks = {"val_a": "val_a\n(rate selected here)", "val_b": "val_b\n(previously seen)",
             "may": "May"}
    for i, h in enumerate(halves):
        p = f"results/{h}/P3/tiers/step_up"
        v = L.row(h, src, P, f"{p}/precision", "bar")
        lo = L.row(h, src, P, f"{p}/ci_low", "CI low")
        hi = L.row(h, src, P, f"{p}/ci_high", "CI high")
        L.row(h, src, P, f"{p}/incidents", "incidents (not plotted)")
        L.row(h, src, P, f"results/{h}/previously_seen", "previously_seen flag (not plotted)")
        ax.bar(i, v, width=0.6, **style[h], **BAR)
        ax.errorbar(i, v, yerr=[[v - lo], [hi - v]], fmt="none", **ERR)
        ax.text(i, hi + 0.012, f"{v:.3f}", ha="center", va="bottom", fontsize=8)
    ax.set_xticks(range(len(halves)), [ticks[h] for h in halves])
    ax.tick_params(axis="x", length=0)
    ax.set_ylim(0, 0.6)
    ax.set_ylabel("Step-up tier precision")
    save(fig, "fig5_stepup_precision", L.sections[-1]["notes"])


# ── Figure 6: ROC-AUC of the S1 constructions ───────────────────────────────

def figure6(L, S1, DIAG, CONF):
    L.section("Figure 6: ROC-AUC of S1 constructions (a), (b), (c), all events", [
        "val_a and val_b: Phase 4b diagnostic D1, one fit (seed 42; (a) uses the cached",
        "Phase 3 decisions, which `phase6_s1.json` confirms bit-identical at seed 42).",
        "(a) and (b) on both halves and (c) on val_a are in `phase4b_diag.json`;",
        "(c) on val_b was reported only in the Phase 4b confirm stage and is read from",
        "`phase4b_confirm.json` `/d1_c_val_b` (it equals `rows/best_C1/event_val_b/roc_auc`,",
        "C1 being variant (c), seed 42). These bars have no interval (single fit).",
        "May: S1, all 2,158,083 May events; bar = mean over seeds 42, 43, 44; error bar",
        "= min to max over the three seeds (not a confidence interval). Labels rounded",
        "to 3 decimals. Dashed line: ROC-AUC 0.5 (chance), a reference, not data.",
    ])
    variants = ("a", "b", "c")
    names = {"a": "(a) maps and fit:\nnon-attack rows",
             "b": "(b) maps: all rows;\nfit: non-attack rows",
             "c": "(c) maps and fit:\nall rows (label-free)"}
    series = (("val_a", LIGHT, None), ("val_b", MID, None), ("May (mean of 3 seeds)", DARK, None))
    fig, ax = plt.subplots(figsize=(16.0 * CM, 7.5 * CM))
    w = 0.26
    for j, v in enumerate(variants):
        va = L.row(f"({v}) val_a", "phase4b_diag.json", DIAG, f"variants/{v}/val_a/roc_auc", "bar")
        if v == "c":
            vb = L.row(f"({v}) val_b", "phase4b_confirm.json", CONF, "d1_c_val_b/roc_auc", "bar")
        else:
            vb = L.row(f"({v}) val_b", "phase4b_diag.json", DIAG, f"variants/{v}/val_b/roc_auc", "bar")
        p = f"variants/{v}/over_seeds/all/roc_auc"
        mm = L.row(f"({v}) May", "phase6_s1.json", S1, f"{p}/mean", "bar (seed mean)")
        mn = L.row(f"({v}) May", "phase6_s1.json", S1, f"{p}/min", "range low (seed min)")
        mx = L.row(f"({v}) May", "phase6_s1.json", S1, f"{p}/max", "range high (seed max)")
        for s in (42, 43, 44):
            L.row(f"({v}) May, seed {s}", "phase6_s1.json", S1,
                  f"variants/{v}/seed_{s}/all/roc_auc", "per-seed (not plotted)")
        for k, (val, (lab, color, _)) in enumerate(zip((va, vb, mm), series)):
            x = j + (k - 1) * w
            ax.bar(x, val, width=w - 0.03, color=color, label=lab if j == 0 else None, **BAR)
            top = val
            if k == 2:
                ax.errorbar(x, val, yerr=[[val - mn], [mx - val]], fmt="none", **ERR)
                top = mx
            ax.text(x, top + 0.012, f"{val:.3f}", ha="center", va="bottom", fontsize=8)
    ax.axhline(0.5, color="black", linestyle=(0, (4, 3)), linewidth=0.7, zorder=0)
    ax.text(3.1, 0.505, "chance\n(0.5)", ha="right", va="bottom", fontsize=8)
    ax.set_xticks(range(len(variants)), [names[v] for v in variants])
    ax.tick_params(axis="x", length=0)
    ax.set_xlim(-0.55, 3.1)
    ax.set_ylim(0, 1.0)
    ax.set_ylabel("ROC-AUC, all events")
    ax.legend(loc="upper right", ncol=3, handletextpad=0.4, columnspacing=1.2)
    save(fig, "fig6_s1_roc_auc", L.sections[-1]["notes"])


def main():
    P = load("phase6_primary.json")
    S1 = load("phase6_s1.json")
    DIAG = load("phase4b_diag.json")
    CONF = load("phase4b_confirm.json")
    assert S1["half"] == "may"
    assert get(P, "results/may/previously_seen") is False
    global WRITE
    stems = {"1": FIG1_STEM, "2": FIG2_STEM,
             "3": "fig3_detector_precision_new_vs_returning", "4": "fig4_budget_curve_T2_vs_T0",
             "5": "fig5_stepup_precision", "6": "fig6_s1_roc_auc"}
    WRITE = {stems[k] for k in sys.argv[1:]} if sys.argv[1:] else None
    L = Ledger()
    figure1(L, save)
    figure2(L, save)
    figure3(L, P, S1)
    figure4(L, P)
    figure5(L, P)
    figure6(L, S1, DIAG, CONF)
    (HERE / "FIGURE_DATA.md").write_text(L.markdown() + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
